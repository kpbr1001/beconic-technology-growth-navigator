/** 문항 번호 표시(대표가 읽는 이름): q9 → '외부 의존·대체방안' 문항, 이름이 없으면 9번 문항 */
export const qRef = (id: string) => {
  const name = Q_SHORT[id];
  if (name) return `'${name}'`;
  const n = id.replace(/^\D+/, '');
  return id.startsWith('d') ? `심화 ${n}번 문항` : `${n}번 문항`;
};
/** 여러 문항 이름 나열 */
export const qRefs = (ids: string[]) => ids.map(qRef).join(', ');
