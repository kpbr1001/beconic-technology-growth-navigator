// ───────────────────────── 먼저 하면 좋은 일 (사실 기반 순서)
// 1) 확인된 차이 해소  2) 이 문항을 채우면 실행 가능한 자동 확인이 늘어나는 순 — 위험도 순위가 아님
const DEPENDS = {
  Q07: ['R-REV-01'], Q20: ['R-REV-01', 'R-GROW-01'], Q21: ['R-CASH-01', 'R-CASH-02'], Q22: ['R-CF-01', 'R-CASH-02'],
  Q09: ['R-CUST-01'], Q10: ['R-RET-01'], Q17: ['R-CAP-01'], Q24: ['R-FUND-01'], Q23: ['R-DECK-01'],
};
const DONE = ['match', 'mismatch', 'calc'];
export function nextActions(ev) {
  const out = [];
  for (const f of ev.findings.filter((x) => x.result === 'mismatch')) {
    const g = guideFor(f);
    out.push({ kind: 'fix', qid: f.qid, fid: f.id, title: `${f.title} — 차이 확인`, text: g ? g.fix[0] : f.request });
  }
  const unlock = [];
  for (const [qid, rules] of Object.entries(DEPENDS)) {
    if (ev.byQ[qid].data === 'na_ok') continue;
    const pending = new Set();
    for (const r of rules) {
      const fs = ev.findings.filter((f) => f.rule === r && f.refs.includes(qid));
      if (r === 'R-DECK-01') { if (fs.some((f) => !DONE.includes(f.result))) pending.add(r); continue; }
      if (!fs.some((f) => DONE.includes(f.result))) pending.add(r);
    }
    // 덱 비교가 원자료(Q07·Q09·Q21) 입력을 기다리는 경우
    for (const f of ev.findings.filter((x) => x.rule === 'R-DECK-01' && x.result === 'incomplete' && x.refs.includes(qid) && qid !== 'Q23')) pending.add(`R-DECK-01:${f.id}`);
    if (pending.size) unlock.push({ kind: 'unlock', qid, n: pending.size, rules: [...pending].map((r) => r.split(':')[0]) });
  }
  unlock.sort((a, b) => b.n - a.n || Q_ORDER.findIndex((q) => q.id === a.qid) - Q_ORDER.findIndex((q) => q.id === b.qid));
  for (const u of unlock) {
    const names = [...new Set(u.rules)].map((r) => RULES[r].name);
    out.push({ ...u, title: `${u.qid} 입력 시 자동 확인 ${u.n}건 가능`, text: names.join(' · ') });
  }
  return out;
}

// ───────────────────────── 섹션별 정리
export function sectionSummary(ev, secId) {
  const qs = QUESTIONS.filter((q) => q.sec === secId); const c = { confirmed: 0, self: 0, none: 0, attention: 0, na: 0 };
  for (const q of qs) {
    const d = ev.byQ[q.id].data;
    if (d === 'linked' || d === 'match') c.confirmed++; else if (d === 'submitted') c.self++; else if (d === 'none' || d === 'na_wait') c.none++; else if (d === 'na_ok') c.na++;
    if (d === 'mismatch') c.attention++;
  }
  const ids = new Set(qs.map((q) => q.id));
  const todo = ev.todo.filter((t) => ids.has(t.qid)).sort((a, b) => TODO_ORDER.indexOf(a.type) - TODO_ORDER.indexOf(b.type));
  const first = todo[0];
  const next = first ? `${first.qid} ${TODO_LABEL[first.type]}` : '확인할 항목 없음';
  const sec = SECTIONS.find((s) => s.id === secId);
  return { ...c, total: qs.length, next, title: sec.title, en: sec.en,
    sentence: `${qs.length}문항 중 원문 연결·일치 ${c.confirmed}, 자가진술 ${c.self}, 미제출 ${c.none}${c.na ? `, 적용 제외 ${c.na}` : ''}${c.attention ? `, 자료 간 차이 ${c.attention}` : ''}. 다음 행동: ${next}.` };
}
