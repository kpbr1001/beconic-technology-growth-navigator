/** 결과 → 가이드(규칙 전용 → 공통 순). 일치·계산 결과에는 가이드가 없다 */
export function guideFor(f) {
  if (!['mismatch', 'blocked', 'incomplete'].includes(f.result)) return null;
  return (RULE_GUIDE[f.rule] || {})[f.result] || GENERIC[f.result] || null;
}

